"""Build results/summary.md: per-run metrics with 95% bootstrap CIs and paired comparisons."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from finqa.eval.metrics import load_jsonl, paired_bootstrap, summarize  # noqa: E402

P = Path("results/preds")
PAIRS = [  # (baseline, treatment) on identical example ids
    ("q35-0.8b_base_direct_val100", "q35-0.8b_sft_direct_val100"),
    ("q35-0.8b_sft_direct_val100", "q35-0.8b_sftsynth_direct_val100"),
    ("q35-0.8b_base_direct_sec_fresh", "q35-0.8b_sft_direct_sec_fresh"),
    ("q35-0.8b_base_direct_financebench_numeric", "q35-0.8b_sft_direct_financebench_numeric"),
    ("q35-0.8b_base_direct_val100", "q35-2b_base_direct_val100"),
]


def pct(m):
    return f"{100*m['mean']:.1f} [{100*m['ci95'][0]:.1f}, {100*m['ci95'][1]:.1f}]" if m else "-"


def main():
    lines = ["# Results summary (auto-generated by scripts/make_tables.py)", "",
             "Accuracy in % with 95% bootstrap CI. `raw` = model's own stated answer (primary matcher: 1% rel. tol., "
             "percent-aware, sign-sensitive). `prog` = model-written DSL program executed by the restricted interpreter "
             "(tool-assisted harness score). `parsed` = answer coverage. Latency = CPU wall time per example (batch 1).", "",
             "| run | n | raw | raw lenient | prog | assisted | parsed | prog valid | latency s (mean) | out tok (mean) |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    runs = {}
    for f in sorted(P.glob("*.jsonl")):
        recs = load_jsonl(f)
        if not recs:
            continue
        s = summarize(recs)
        runs[f.stem] = recs
        Path(str(f) + ".summary.json").write_text(json.dumps(s, indent=2))
        lines.append(f"| {f.stem} | {s['n']} | {pct(s.get('correct'))} | {pct(s.get('correct_lenient'))} | "
                     f"{pct(s.get('prog_correct'))} | {pct(s.get('assisted_correct'))} | {pct(s.get('answer_parsed'))} | "
                     f"{pct(s.get('program_ok'))} | {s.get('latency_s', {}).get('mean', 0):.1f} | "
                     f"{s['tokens']['output_mean']:.1f} |")
    lines += ["", "## Paired comparisons (treatment - baseline, same example ids)", "",
              "| baseline | treatment | metric | n | acc A | acc B | diff | 95% CI | McNemar p |", "|---|---|---|---|---|---|---|---|---|"]
    out = {}
    for a, b in PAIRS:
        if a in runs and b in runs:
            for m in ["correct", "prog_correct", "assisted_correct"]:
                r = paired_bootstrap(runs[a], runs[b], m)
                if not r.get("n"):
                    continue
                out[f"{a}__vs__{b}__{m}"] = r
                lines.append(f"| {a} | {b} | {m} | {r['n']} | {100*r['acc_a']:.1f} | {100*r['acc_b']:.1f} | "
                             f"{100*r['diff_b_minus_a']:+.1f} | [{100*r['ci95'][0]:+.1f}, {100*r['ci95'][1]:+.1f}] | {r['mcnemar_exact_p']:.2g} |")
    Path("results/summary.md").write_text("\n".join(lines) + "\n")
    Path("results/paired_comparisons.json").write_text(json.dumps(out, indent=2))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
